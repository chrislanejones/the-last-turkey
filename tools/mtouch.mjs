import { chromium } from 'playwright-core'
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] })
const ctx = await b.newContext({ viewport: { width: 844, height: 390 }, isMobile: true, hasTouch: true })
const p = await ctx.newPage(); p.on('pageerror', e => console.log('ERR', e.message))
await p.goto('http://localhost:8765/?shot', { waitUntil: 'load' })
await p.waitForFunction(() => window.__game, null, { timeout: 180000 })
await p.tap('#playBtn'); await p.evaluate(() => window.__game.sim(6))
const brake = await p.$('[data-touch=brake]'); const bb = await brake.boundingBox()
const before = await p.evaluate(() => [window.__game.P.pos.x, window.__game.P.pos.y])
await brake.dispatchEvent('pointerdown', { pointerId: 5 }); await p.evaluate(() => window.__game.sim(1.5)); await brake.dispatchEvent('pointerup', { pointerId: 5 })
const after = await p.evaluate(() => [window.__game.P.pos.x, window.__game.P.pos.y, window.__game.game.state])
await p.evaluate(() => window.__game.game.sodaReady = true)
const s0 = await p.evaluate(() => window.__game.game.soda); await p.tap('#sodaBtn'); const s1 = await p.evaluate(() => window.__game.game.soda)
console.log('moved', Math.hypot(after[0]-before[0], after[1]-before[1]).toFixed(1), 'm', after[2], 'soda', s0, '->', s1, 'brake btn', JSON.stringify(bb))
await b.close()
